"""Collect one growth stage into images/ and labels/ without changing annotations."""

from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
from pathlib import Path
from typing import Any


IMAGE_EXTENSIONS = (".jpg", ".JPG", ".jpeg", ".JPEG", ".png", ".PNG", ".bmp", ".BMP")


def args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--table", type=Path, default=Path("stage_file2.txt"),
                        help="TSV generated by stage_split.py")
    parser.add_argument("--data-root", type=Path, required=True,
                        help="Root directory containing the source JSON and images")
    parser.add_argument("--stage", required=True,
                        help="Growth stage to collect, for example V3-V5")
    parser.add_argument("--source", required=True, choices=("UAV", "DSLR"),
                        help="Source directory to collect")
    parser.add_argument("--output", type=Path, default=None,
                        help="Output directory; default is stage_<stage>")
    parser.add_argument("--copy", action="store_true",
                        help="Copy images instead of using hard links when possible")
    return parser.parse_args()


def source_of(category: str) -> str:
    """Use the same source rule as split_by_source.py."""
    return "UAV" if category.upper().rstrip().endswith("UAV") else "DSLR"


def find_by_name(root: Path, name: str) -> Path | None:
    path = root / name
    if path.is_file():
        return path
    matches = [match for match in root.rglob(Path(name).name) if match.is_file()]
    return matches[0] if matches else None


def find_image(
    json_path: Path,
    data: dict[str, Any],
    root: Path,
    table_name: str,
) -> Path | None:
    image_path = str(data.get("imagePath") or "").strip().replace("\\", "/")
    names = [Path(image_path).name] if image_path else []
    names.append(Path(table_name).name)
    names.append(json_path.stem)

    for name in names:
        candidates = [json_path.parent / name, root / name]
        candidates.extend(json_path.parent / (Path(name).stem + ext) for ext in IMAGE_EXTENSIONS)
        candidates.extend(root.rglob(Path(name).name))
        for candidate in candidates:
            if candidate.is_file() and candidate.suffix in IMAGE_EXTENSIONS:
                return candidate
    return None


def load_samples(
    table: Path,
    root: Path,
    wanted_stage: str,
    source: str,
) -> list[tuple[Path, Path]]:
    samples: list[tuple[Path, Path]] = []
    seen: set[Path] = set()
    with table.open("r", encoding="utf-8-sig", newline="") as file:
        header = file.readline().rstrip("\r\n").split("\t")
        columns = {value.strip().lower(): index for index, value in enumerate(header)}
        required = {"category", "stage", "filename", "json_filename"}
        missing = required - set(columns)
        if missing:
            raise ValueError(f"Missing table columns: {', '.join(sorted(missing))}")

        for line_number, line in enumerate(file, 2):
            values = line.rstrip("\r\n").split("\t")
            stage = values[columns["stage"]].strip()
            if stage.casefold() != wanted_stage.casefold():
                continue
            category = values[columns["category"]].strip()
            if source_of(category) != source:
                continue
            json_name = values[columns["json_filename"]].strip()
            json_path = find_by_name(root, json_name)
            if json_path is None:
                print(f"Warning: line {line_number}: JSON not found: {json_name}", file=sys.stderr)
                continue
            try:
                with json_path.open("r", encoding="utf-8") as json_file:
                    data = json.load(json_file)
            except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
                print(f"Warning: cannot read {json_path}: {error}", file=sys.stderr)
                continue
            image_path = find_image(
                json_path,
                data,
                root,
                values[columns["filename"]].strip(),
            )
            if image_path is None:
                print(f"Warning: image not found for {json_path}", file=sys.stderr)
                continue
            if image_path in seen:
                print(f"Warning: duplicate image skipped: {image_path}", file=sys.stderr)
                continue
            seen.add(image_path)
            samples.append((json_path, image_path))
    return samples


def place_file(source: Path, destination: Path, force_copy: bool) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    if destination.exists():
        destination.unlink()
    if not force_copy:
        try:
            os.link(source, destination)
            return
        except OSError:
            pass
    shutil.copy2(source, destination)


def main() -> int:
    command = args()
    output = command.output or Path(f"stage_{command.stage}_{command.source}")
    if not command.table.is_file():
        print(f"Error: table not found: {command.table}", file=sys.stderr)
        return 1
    if not command.data_root.is_dir():
        print(f"Error: data root not found: {command.data_root}", file=sys.stderr)
        return 1

    try:
        samples = load_samples(command.table, command.data_root, command.stage, command.source)
        if not samples:
            raise ValueError(f"No usable files found for stage: {command.stage}")
        written = 0
        for json_path, image_path in samples:
            image_output = output / "images" / image_path.name
            label_output = output / "labels" / json_path.name
            place_file(image_path, image_output, command.copy)
            place_file(json_path, label_output, command.copy)
            written += 1
    except (OSError, ValueError, json.JSONDecodeError) as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1

    print(f"Created {written} samples in {output}")
    print(f"  images: {output / 'images'}")
    print(f"  labels: {output / 'labels'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
